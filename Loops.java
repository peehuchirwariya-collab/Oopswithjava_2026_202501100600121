public class Loops {
    public static void main(String[] args){
        // loops
        int m=1; // 1 t0 10
        System.out.println(m);
        m++;
        // very long code ;
        // use loops

        // while loops
        int i = 1;
        while(i<= 10  ){ // boolean -> true / false 
            System.out.println(i);
            i++;
        }
        /*
         while(expression ){
         //do something ;
         }
        */



        // do while loop
    /*
        do{
        //do something 
        } while(expression);

    */

      do {
       System.out.println(i);
       i++;
      } while(i <= 10 );



    //for loop 
    /*
    for(initialization ; condition  ; increment ){
    }
     */

    for (int a=0 ; a<=10 ; a++){
        System.out.println(a);

    }
    // flow of control of for:
    



    }
}